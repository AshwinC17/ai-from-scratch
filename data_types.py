# Python Data Types

# Integer
age = 24

# Float
height = 5.11

# String
name = "Ashwin"

# Boolean
is_learning_ai = True

# Print values
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Learning AI:", is_learning_ai)

# Check data types
print(type(name))
print(type(age))
print(type(height))
print(type(is_learning_ai))